//! Q CLI ACP Agent - Agent Client Protocol server for Q CLI
//!
//! This binary runs the Q CLI backend as an ACP agent, communicating over stdio.
//! 
//! To test:
//! ```bash
//! cargo build --bin q_agent --bin q_client
//! cargo run --bin q_client -- target/debug/q_agent
//! ```

use agent_client_protocol::{self as acp, AgentSideConnection, Client as _};
use chat_cli_ui::protocol::Event;
use chat_cli_ui::conduit::initialize_conduit;
use chat_cli::cli::chat::{ChatArgs, ChatState};
use chat_cli::os::Os;
use tokio::sync::mpsc::{Receiver, Sender};
use tokio_util::compat::{TokioAsyncReadCompatExt, TokioAsyncWriteCompatExt};
use eyre::Result;

// This component converts from Conduit structured event to ACP Client SessionUpdate
struct SessionUpdateSender {
    session_id: acp::SessionId,
}

impl SessionUpdateSender {
    fn new(session_id: acp::SessionId) -> Self {
        Self { session_id }
    }

    fn spawn_event_processor(&self,
        event_receiver: std::sync::mpsc::Receiver<Event>,
        acp_connection: AgentSideConnection
    ) {
        let session_id = self.session_id.clone();
        
        tokio::task::spawn_blocking(move || {
            // take Conduit event generated by Chat Session
            while let Ok(event) = event_receiver.recv() {
                // convert it to ACP 
                if let Some(session_notification) = Self::convert_event_to_session_notification(event, &session_id) {
                    let _ = acp_connection.session_notification(session_notification);
                }
            }
        });
    }

    fn convert_event_to_session_notification(event: Event, session_id: &acp::SessionId) -> Option<acp::SessionNotification> {
        match event {
            Event::TextMessageContent(content) => {
                Some(acp::SessionNotification {
                    session_id: session_id.clone(),
                    update: acp::SessionUpdate::AgentMessageChunk(acp::ContentChunk {
                        content: acp::ContentBlock::Text(acp::TextContent {
                            text: String::from_utf8_lossy(&content.delta).to_string(),
                            annotations: None,
                            meta: None,
                        }),
                        meta: None,
                    }),
                    meta: None,
                })
            },
            _ => None,
        }
    }
}

struct QCliAgent {
    session_id: acp::SessionId,
    user_input_sender: Sender<String>,
}

impl QCliAgent {
    async fn new() -> (Self, Receiver<String>) {
        let session_id: agent_client_protocol::SessionId = acp::SessionId("Session-42".into());


        // Channel for user_prompt from ACP client
        // Sender is the ACP UserPrompt callback
        // Receiver is ChatSession
        let (user_input_sender, user_input_receiver) = tokio::sync::mpsc::channel::<String>(32);

        return (Self {session_id, user_input_sender,}, user_input_receiver);
    }
}

#[async_trait::async_trait(?Send)]
impl acp::Agent for QCliAgent {
    async fn initialize(
        &self,
        _arguments: acp::InitializeRequest,
    ) -> Result<acp::InitializeResponse, acp::Error> {
        Ok(acp::InitializeResponse {
            protocol_version: acp::V1,
            agent_capabilities: acp::AgentCapabilities {
                load_session: false,
                prompt_capabilities: acp::PromptCapabilities {
                    image: false,
                    audio: false,
                    embedded_context: true,
                    meta: None,
                },
                mcp_capabilities: acp::McpCapabilities {
                    http: false,
                    sse: false,
                    meta: None,
                },
                meta: None,
            },
            auth_methods: Vec::new(),
            agent_info: Some(acp::Implementation {
                name: "q-cli-agent".to_string(),
                title: Some("Amazon Q CLI Agent".to_string()),
                version: env!("CARGO_PKG_VERSION").to_string(),
            }),
            meta: None,
        })
    }

    async fn authenticate(
        &self,
        _arguments: acp::AuthenticateRequest,
    ) -> Result<acp::AuthenticateResponse, acp::Error> {
        Ok(acp::AuthenticateResponse::default())
    }

    async fn new_session(
        &self,
        _arguments: acp::NewSessionRequest,
    ) -> Result<acp::NewSessionResponse, acp::Error> {
        Ok(acp::NewSessionResponse {
            session_id: self.session_id.clone(),
            modes: None,
            meta: None,
        })
    }

    // Not supported for now.
    async fn load_session(
        &self,
        _arguments: acp::LoadSessionRequest,
    ) -> Result<acp::LoadSessionResponse, acp::Error> {
        Err(acp::Error::method_not_found())
    }

    // Process a prompt from Client
    async fn prompt(
        &self,
        arguments: acp::PromptRequest,
    ) -> Result<acp::PromptResponse, acp::Error> {
        // Extract text from prompt content
        let mut prompt_text = String::new();
        for content in arguments.prompt {
            match content {
                acp::ContentBlock::Text(text_content) => {
                    prompt_text.push_str(&text_content.text);
                }
                _ => {
                    // For now, ignore non-text content
                }
            }
        }

        // send prompt_text to user_input queue
        // ChatSession will pick it up
        self.user_input_sender.send(prompt_text).await.unwrap();

        // TODO: Agent should really only return this when it have completed everything in this turn. (i.e. return LLM response, call tool, etc)
        Ok(acp::PromptResponse {
            stop_reason: acp::StopReason::EndTurn,
            meta: None,
        })
    }

    async fn cancel(&self, _args: acp::CancelNotification) -> Result<(), acp::Error> {
        Ok(())
    }

    async fn set_session_mode(
        &self,
        _args: acp::SetSessionModeRequest,
    ) -> Result<acp::SetSessionModeResponse, acp::Error> {
        Ok(acp::SetSessionModeResponse::default())
    }

    async fn ext_method(&self, _args: acp::ExtRequest) -> Result<acp::ExtResponse, acp::Error> {
        Err(acp::Error::method_not_found())
    }

    async fn ext_notification(&self, _args: acp::ExtNotification) -> Result<(), acp::Error> {
        Ok(())
    }
}

#[tokio::main(flavor = "current_thread")]
async fn main() -> acp::Result<()> {
    // Initialize logging
    tracing_subscriber::fmt::init();

    let outgoing = tokio::io::stdout().compat_write();
    let incoming = tokio::io::stdin().compat();

    let local_set = tokio::task::LocalSet::new();
    local_set
        .run_until(async move {

            // Create the agent
            let (agent, user_input_receiver) = QCliAgent::new().await;

            // Initialize conduit
            // chat_event_receiver is used to receive Conduit events from ChatSession
            let (control_end_stderr, control_end_stdout, chat_event_receiver) = initialize_conduit();

            // SessionUpdateSender poll structured events (emitted by ChatSession) and send them to ACP Client
            // This doesn't make sense. SessionUpdateSender should send the request to ACP connection!
            let session_update_sender = SessionUpdateSender::new(agent.session_id.clone());
            
            // Create chat session
            let mut os = Os::new().await.unwrap();
            let chat_args = ChatArgs {
                resume: false,
                agent: None,
                model: None,
                trust_all_tools: false,
                trust_tools: None,
                no_interactive: true,
                input: None,
                wrap: None,
            };
            let mut chat_session = chat_args.create_chat_session(
                &mut os, 
                user_input_receiver, 
                control_end_stderr, 
                control_end_stdout
            ).await.unwrap();

            // Spawn ChatSession state machine to run in background
            let mut os = Os::new().await.unwrap();
            tokio::task::spawn_local(async move {
                while !matches!(chat_session.inner, Some(ChatState::Exit)) {
                    if let Err(e) = chat_session.next(&mut os).await {
                        eprintln!("ChatSession error: {e}");
                        break;
                    }
                }
            });

            // Start up the agent connected to stdio
            let (conn, handle_io) =
                acp::AgentSideConnection::new(agent, outgoing, incoming, |fut| {
                    tokio::task::spawn_local(fut);
                });

            // Start the Conduit -> ACP Client event processing
            session_update_sender.spawn_event_processor(chat_event_receiver, conn);
            
            // Run until stdin/stdout are closed
            handle_io.await
        })
        .await
}